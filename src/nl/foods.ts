const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-")

export type AnyFood = Food & {
  emoji?: string
  aliases?: string
  estimated?: boolean
  source?: string
  food_id?: number
  slug?: string
}

export const LIBRARY: AnyFood[] = [
  ...FOODS.map((f) => ({ ...f, aliases: f.id })),
  ...ROWS.map(
    ([
      name,
      tag,
      unit,
      kcal,
      protein,
      carbs,
      fat,
      fiber,
      sugar,
      sodium,
      emoji,
      aliases,
    ]) => ({
      id: slug(name),
      name,
      tag,
      unit,
      kcal,
      protein,
      carbs,
      fat,
      fiber,
      sugar,
      sodium,
      emoji,
      aliases,
      img: "",
    }),
  ),
]

const norm = (s: string) =>
  s.toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
// strip plurals so "pizzas" → "pizza", "tacos" → "taco"
const stem = (w: string) =>
  w.length > 3 && w.endsWith("es") && !w.endsWith("ses")
    ? w.slice(0, -2)
    : w.length > 3 && w.endsWith("s")
      ? w.slice(0, -1)
      : w

export function searchFoods(query: string): AnyFood[] {
  const q = norm(query)
  if (!q) return LIBRARY.slice(0, 4)
  const words = q
    .split(" ")
    .filter((w) => w.length > 1 && !/^\d+$/.test(w))
    .map(stem)
  const scored = LIBRARY.map((f) => {
    const hay = norm(`${f.name} ${f.aliases ?? ""} ${f.tag}`)
    const name = norm(f.name)
    let score = 0
    if (name === q) score += 100
    if (name.includes(q)) score += 40
    const hayWords = hay.split(/\s+/)
    for (const w of words) {
      if (name.split(/\s+/).some((n) => stem(n) === w || n === w)) score += 20
      else if (
        hayWords.some(
          (hw) =>
            stem(hw) === w || hw === w || (w.length >= 4 && hw.startsWith(w)),
        )
      )
        score += 8
    }
    return { f, score }
  })
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((r) => r.f)
  return scored.slice(0, 8)
}

