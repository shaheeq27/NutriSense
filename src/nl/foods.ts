export function estimateFood(query: string): AnyFood {
  const q = norm(query)
  const name = q.replace(/\b\w/g, (m) => m.toUpperCase()) || "Your food"
  const qty = Number(q.match(/^(\d+(\.\d+)?)\b/)?.[1] ?? 1)
  const base = PROFILES.find(([re]) => re.test(q))?.[1] ?? {
    tag: "Mixed dish • Estimate",
    unit: "serving",
    kcal: 400,
    protein: 15,
    carbs: 45,
    fat: 17,
    fiber: 4,
    sugar: 6,
    sodium: 650,
    emoji: "🍽️",
  }
  const m = qty > 0 && qty < 20 ? qty : 1
  const r = (n: number) => Math.round(n * m * 10) / 10
  return {
    ...base,
    id: `est-${slug(q)}`,
    name: name.replace(/^\d+(\.\d+)?\s*/, "") || name,
    img: "",
    estimated: true,
    unit: m === 1 ? base.unit : `${m} × ${base.unit}`,
    kcal: Math.round(base.kcal * m),
    protein: r(base.protein),
    carbs: r(base.carbs),
    fat: r(base.fat),
    fiber: r(base.fiber),
    sugar: r(base.sugar),
    sodium: Math.round(base.sodium * m),
  }
}

/** Best emoji for any food name: canonical resolver first, then search, then estimator's guess. */
export function emojiFor(name: string, fallback = "🍽️") {
  const canonical = getFoodEmoji({ name })
  if (canonical && canonical !== "🍽️") return canonical
  const first = name.split("+")[0]
  return (
    searchFoods(first).find((f) => f.emoji)?.emoji ??
    estimateFood(first).emoji ??
    fallback
  )
}
